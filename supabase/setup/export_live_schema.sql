-- Builds a complete, re-runnable setup script for the Dudex public schema
-- (plus auth.users triggers, storage buckets/policies, realtime) from the
-- live catalog. Read-only: only SELECTs against pg_catalog.
with
pub as (select 'public'::regnamespace as ns),
ext_objs as (select objid from pg_depend where deptype = 'e'),
tbl as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relacl, c.relowner
  from pg_class c, pub
  where c.relnamespace = pub.ns and c.relkind in ('r','p')
    and c.oid not in (select objid from ext_objs)
),
s_ext as (
  select coalesce(string_agg(format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname), E'\n' order by e.extname), '') as t
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname not in ('plpgsql','pg_graphql','pg_stat_statements','supabase_vault','pgsodium','pgjwt')
),
s_enum as (
  select coalesce(string_agg(format('DO $e$ BEGIN CREATE TYPE public.%I AS ENUM (%s); EXCEPTION WHEN duplicate_object THEN NULL; END $e$;',
    t.typname, (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid = t.oid)), E'\n' order by t.typname), '') as t
  from pg_type t, pub where t.typnamespace = pub.ns and t.typtype = 'e'
),
s_seq as (
  select coalesce(string_agg(format('CREATE SEQUENCE IF NOT EXISTS public.%I;', c.relname), E'\n' order by c.relname), '') as t
  from pg_class c, pub where c.relnamespace = pub.ns and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),
s_tables as (
  select string_agg(
    format(E'CREATE TABLE IF NOT EXISTS public.%I (\n%s%s\n);', t.relname,
      (select string_agg(
          '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
          || case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY' when 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end
          || case when a.attgenerated = 's' then ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                  when d.adbin is not null then ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) else '' end
          || case when a.attnotnull then ' NOT NULL' else '' end,
          E',\n' order by a.attnum)
       from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
       where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped),
      coalesce((select E',\n' || string_agg(format('  CONSTRAINT %I %s', con.conname, pg_get_constraintdef(con.oid)), E',\n' order by con.contype desc, con.conname)
                from pg_constraint con where con.conrelid = t.oid and con.contype in ('p','u','c','x')), '')
    ), E'\n\n' order by t.relname) as t
  from tbl t
),
s_fk as (
  select coalesce(string_agg(format(
    E'DO $f$ BEGIN ALTER TABLE public.%I ADD CONSTRAINT %I %s; EXCEPTION WHEN duplicate_object THEN NULL; END $f$;',
    t.relname, con.conname, pg_get_constraintdef(con.oid)), E'\n' order by t.relname, con.conname), '') as t
  from pg_constraint con join tbl t on t.oid = con.conrelid where con.contype = 'f'
),
s_views as (
  select coalesce(string_agg(format(E'CREATE OR REPLACE VIEW public.%I%s AS\n%s', c.relname,
    case when c.reloptions is not null then ' WITH (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
    pg_get_viewdef(c.oid, true)), E'\n\n' order by c.relname), '') as t
  from pg_class c, pub where c.relnamespace = pub.ns and c.relkind = 'v'
    and c.oid not in (select objid from ext_objs)
),
fns as (
  select p.oid, p.proacl, p.proowner,
    format('public.%I(%s)', p.proname, pg_get_function_identity_arguments(p.oid)) as sig
  from pg_proc p, pub where p.pronamespace = pub.ns and p.prokind in ('f','p')
    and p.oid not in (select objid from ext_objs)
),
s_fns as (
  select coalesce(string_agg(pg_get_functiondef(f.oid) || ';', E'\n\n' order by f.sig), '') as t from fns f
),
s_idx as (
  select coalesce(string_agg(
    regexp_replace(pg_get_indexdef(i.indexrelid), '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || ';',
    E'\n' order by t.relname, i.indexrelid::regclass::text), '') as t
  from pg_index i join tbl t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid and con.contype in ('p','u','x'))
),
s_trg as (
  select coalesce(string_agg(format(E'DROP TRIGGER IF EXISTS %I ON %s;\n%s;', tg.tgname, tg.tgrelid::regclass, pg_get_triggerdef(tg.oid)),
    E'\n' order by tg.tgrelid::regclass::text, tg.tgname), '') as t
  from pg_trigger tg
  where not tg.tgisinternal
    and (tg.tgrelid in (select oid from tbl) or tg.tgrelid = 'auth.users'::regclass)
),
s_rls as (
  select coalesce(string_agg(format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t.relname)
    || case when t.relforcerowsecurity then format(' ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', t.relname) else '' end,
    E'\n' order by t.relname), '') as t
  from tbl t where t.relrowsecurity
),
s_pol as (
  select coalesce(string_agg(format(E'DROP POLICY IF EXISTS %I ON %I.%I;\nCREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
    p.policyname, p.schemaname, p.tablename,
    p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
    (select string_agg(quote_ident(r), ', ') from unnest(p.roles) r),
    case when p.qual is not null then E'\n  USING (' || p.qual || ')' else '' end,
    case when p.with_check is not null then E'\n  WITH CHECK (' || p.with_check || ')' else '' end),
    E'\n' order by p.schemaname, p.tablename, p.policyname), '') as t
  from pg_policies p
  where p.schemaname = 'public' or (p.schemaname = 'storage' and p.tablename = 'objects')
),
s_tgrant as (
  select coalesce(string_agg(g, E'\n' order by g), '') as t from (
    select format('GRANT %s ON public.%I TO %s;', string_agg(distinct a.privilege_type, ', '), t.relname,
      case when a.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(a.grantee)) end) as g
    from tbl t, lateral aclexplode(coalesce(t.relacl, acldefault('r', t.relowner))) a
    where a.grantee = 0 or pg_get_userbyid(a.grantee) in ('anon','authenticated','service_role')
    group by t.relname, a.grantee
    union all
    select format('GRANT SELECT ON public.%I TO %s;', c.relname, quote_ident(pg_get_userbyid(a.grantee)))
    from pg_class c, pub, lateral aclexplode(coalesce(c.relacl, acldefault('r', c.relowner))) a
    where c.relnamespace = pub.ns and c.relkind = 'v' and a.privilege_type = 'SELECT'
      and pg_get_userbyid(a.grantee) in ('anon','authenticated','service_role')
  ) x
),
s_fgrant as (
  select coalesce(string_agg(g, E'\n' order by g), '') as t from (
    select format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated;', f.sig) as g from fns f
    union all
    select format('GRANT EXECUTE ON FUNCTION %s TO %s;', f.sig,
      case when a.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(a.grantee)) end)
    from fns f, lateral aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) a
    where a.privilege_type = 'EXECUTE'
      and (a.grantee = 0 or pg_get_userbyid(a.grantee) in ('anon','authenticated','service_role'))
  ) x
),
s_buckets as (
  select coalesce(string_agg(format(
    'INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %s, %s, %s) ON CONFLICT (id) DO NOTHING;',
    b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'NULL'),
    coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'NULL')), E'\n' order by b.id), '') as t
  from storage.buckets b
),
s_rt as (
  select coalesce(string_agg(format(
    'DO $r$ BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE %I.%I; EXCEPTION WHEN duplicate_object THEN NULL; END $r$;',
    schemaname, tablename), E'\n' order by tablename), '') as t
  from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public'
)
select concat_ws(E'\n\n',
  '-- ===== 1. Extensions =====', (select t from s_ext),
  '-- ===== 2. Enum types =====', (select t from s_enum),
  '-- ===== 3. Sequences =====', (select t from s_seq),
  '-- ===== 4. Tables =====', (select t from s_tables),
  '-- ===== 5. Foreign keys =====', (select t from s_fk),
  '-- ===== 6. Views =====', (select t from s_views),
  '-- ===== 7. Functions =====', (select t from s_fns),
  '-- ===== 8. Indexes =====', (select t from s_idx),
  '-- ===== 9. Triggers =====', (select t from s_trg),
  '-- ===== 10. Row level security =====', (select t from s_rls),
  '-- ===== 11. Policies =====', (select t from s_pol),
  '-- ===== 12. Table privileges =====',
  'REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;', (select t from s_tgrant),
  '-- ===== 13. Function privileges =====', (select t from s_fgrant),
  '-- ===== 14. Storage buckets =====', (select t from s_buckets),
  '-- ===== 15. Realtime =====', (select t from s_rt)
)
